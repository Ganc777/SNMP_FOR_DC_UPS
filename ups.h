// Логика ИБП: анализ напряжений, пороги с гистерезисом,
// оценка заряда по нелинейной кривой Li-ion, прогноз runtime.
//
// R10: добавлена upsFormatStatusBlock() — формирует текстовый
//      блок со статусом ИБП для уведомлений TG/EM.
//==============================================================

#ifndef UPS_H
#define UPS_H

#include <Arduino.h>
#include "storage.h"

//--------------------------------------------------------------
// Состояния ИБП (для дашборда, лога, SNMP)
//--------------------------------------------------------------
enum UpsState : uint8_t {
    UPS_STATE_NORMAL   = 0,   // вход есть, батарея в норме
    UPS_STATE_INPUT_LOST = 1, // вход пропал, работаем от батареи
    UPS_STATE_LOW_BATT   = 2, // батарея ниже 7,0 В
    UPS_STATE_CRITICAL   = 3  // батарея ниже 6,0 В (пора выключать QNAP)
};

//--------------------------------------------------------------
// Структура с результатами логики ИБП
//--------------------------------------------------------------
struct UpsStatus {
    UpsState state;

    bool  inputPresent;        // true — 12 В на входе есть
    bool  batteryLow;          // ниже warn-порога
    bool  batteryCritical;     // ниже empty-порога

    float batteryVolts;        // последнее измеренное напряжение батареи
    float inputVolts;          // последнее измеренное напряжение входа

    uint8_t batteryPercent;    // 0..100

    // Runtime в секундах. Если вход есть — 0 (не актуально).
    // Если работаем от батареи — оставшееся время.
    uint32_t runtimeSec;

    // Аптайм с момента пропадания входа (сек). 0, если вход есть.
    uint32_t secondsOnBattery;

    // Аптайм с момента последнего восстановления входа (сек)
    uint32_t secondsSinceInputRestore;
};

//--------------------------------------------------------------
// API
//--------------------------------------------------------------
// Инициализация модуля
void upsInit(const Config &cfg);

// Обновление логики ИБП. Вызывать в loop() на каждом круге
// (не реже, чем раз в 100 мс — используется для таймеров).
// Возвращает true, если изменилось состояние (нужно логировать).
bool upsUpdate(const Config &cfg,
               float batteryVolts,
               float inputVolts);

// Получить текущий статус
UpsStatus upsGetStatus();

//--------------------------------------------------------------
// Утилиты
//--------------------------------------------------------------
// Строковое имя состояния (для лога, web, SNMP)
const char* upsStateName(UpsState st);

// Рассчитать процент заряда Li-ion по нелинейной кривой.
// Диапазон: cfg.battEmptyV..cfg.battFullV -> 0..100 %
uint8_t upsCalcBatteryPercent(float volts, const Config &cfg);

// Рассчитать runtime (сек) по текущему заряду и нагрузке.
// Упрощённая модель: E_остаток (Вт·ч) = capacity × percent / 100
//                      P_нагрузка = loadCurrentA × 12 В (примерно)
//                      t = E_остаток / P_нагрузка
uint32_t upsCalcRuntimeSec(uint8_t percent, const Config &cfg);

//--------------------------------------------------------------
// R10: формирование блока статуса для уведомлений TG/EM.
//
// Возвращает многострочный текст вида:
//   🔋 Батарея: 7.774 В (73%)
//   ⚡ Вход:    12.131 В (OK)
//   ⏱ Runtime: 46 мин 49 с
//   🌡️ Температура CPU: 53.3 °C
//   ℹ️ Состояние: NORMAL
//
// Если withEmoji == false, эмодзи не подставляются (на случай
// клиентов, которые их не поддерживают).
//--------------------------------------------------------------
String upsFormatStatusBlock(bool withEmoji = true);

#endif // UPS_H

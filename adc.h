// Модуль чтения АЦП: медиана + среднее, пересчёт через
// коэффициент делителя, калибровка (смещение + множитель).
// Два канала: BATTERY (IO36) и INPUT (IO39).
//==============================================================

#ifndef ADC_H
#define ADC_H

#include <Arduino.h>
#include "storage.h"

//--------------------------------------------------------------
// Структура с обработанными значениями одного канала
//--------------------------------------------------------------
struct AdcChannel {
    uint16_t rawMv;        // последнее "сырое" значение ADC в мВ (до усреднения)
    uint16_t filteredMv;   // после медианы + среднего (до пересчёта)
    float    adcVolts;     // напряжение на входе ADC после фильтра, В
    float    realVolts;    // реальное напряжение (после делителя и калибровки), В
};

//--------------------------------------------------------------
// Инициализация модуля (настройка затухания, разрешения)
//--------------------------------------------------------------
void adcInit();

//--------------------------------------------------------------
// Однократное обновление обоих каналов.
// Вызывать из loop() с периодом cfg.adcPollMs.
//--------------------------------------------------------------
void adcUpdate(const Config &cfg);

//--------------------------------------------------------------
// Получить результаты
//--------------------------------------------------------------
AdcChannel adcGetBattery();
AdcChannel adcGetInput();

//--------------------------------------------------------------
// Однократное "сырое" чтение (без фильтра) — для калибровки
// Возвращает mV на входе ADC.
//--------------------------------------------------------------
uint16_t adcReadRawMv(uint8_t pin);

//--------------------------------------------------------------
// Пересчёт: сырое mV ADC -> реальное напряжение с учётом
// делителя и калибровки.
//   realV = ((rawMv + offsetMv) / 1000.0) / K * gain
// Параметры offsetMv и gain берутся из Config.
//--------------------------------------------------------------
float adcConvertToReal(uint16_t rawMv, float offsetMv, float gain);

//--------------------------------------------------------------
// Быстрый одиночный замер реального напряжения на канале
// (для калибровочного мастера в дашборде).
//--------------------------------------------------------------
float adcReadRealBattery(const Config &cfg);
float adcReadRealInput(const Config &cfg);

#endif // ADC_H

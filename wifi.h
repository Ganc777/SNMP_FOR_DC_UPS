// Подключение к Wi-Fi (SSID/пароль/статика из Config),
// автоматическое переподключение, логирование потери и
// восстановления связи, вывод IP/RSSI/статуса.
//==============================================================

#ifndef WIFI_H
#define WIFI_H

#include <Arduino.h>
#include "storage.h"

//--------------------------------------------------------------
// Состояния модуля Wi-Fi
//--------------------------------------------------------------
enum WifiState : uint8_t {
    WIFI_ST_DISCONNECTED = 0,
    WIFI_ST_CONNECTING   = 1,
    WIFI_ST_CONNECTED    = 2,
    WIFI_ST_FAILED       = 3
};

//--------------------------------------------------------------
// API
//--------------------------------------------------------------
// Инициализация модуля (вызывать в setup() после storageLoad)
void wifiInit(const Config &cfg);

// Основной цикл: следит за состоянием, переподключается.
// Вызывать в loop() на каждом круге.
void wifiLoop();

// Текущее состояние
WifiState wifiGetState();

// Строковое имя состояния (для лога и web)
const char* wifiStateName(WifiState st);

// Параметры текущего соединения
String   wifiGetIP();
int32_t  wifiGetRSSI();       // dBm (обычно -30..-90)
String   wifiGetSSID();

// Принудительно переподключиться (для web-кнопки)
void wifiReconnect();

#endif // WIFI_H

// Синхронизация времени по NTP + работа с часовым поясом.
// R09.0: периодическая синхронизация раз в сутки в 11:30.
// R09.5: добавлена ntpSetConfig() — применение новых серверов
//        и TZ без перезагрузки. Функция вызывается из web при
//        сохранении конфига.
//==============================================================

#ifndef NTP_H
#define NTP_H

#include <Arduino.h>
#include "storage.h"

// Инициализация (в setup(), после wifiInit)
void ntpInit(const Config &cfg);

// R09.5: применить новую конфигурацию NTP без перезагрузки
// (серверы, TZ, флаг использования NTP).
void ntpSetConfig(const Config &cfg);

// Основной цикл — проверяет расписание (11:30 раз в сутки)
void ntpLoop();

// Принудительная синхронизация NTP (кнопка из дашборда)
void ntpForceSync();

// Синхронизировано ли время
bool ntpIsSynced();

// Текущее время в формате "2026-09-26 13:45:22"
String ntpDateTimeStr();

// Текущая дата "2026-09-26"
String ntpDateStr();

// Текущее время "13:45:22"
String ntpTimeStr();

// Время с точностью до секунд (unix)
uint32_t ntpUnixTime();

#endif // NTP_H

// Синхронизация времени по NTP + работа с часовым поясом.
// Окно плановой синхронизации 1 час, время начала настраивается.
//
// История:
//   R03.0: NTP-синхронизация, часовые пояса, ручная кнопка.
//   R03.1: tzset() перед каждым localtime_r().
//   R07.7: убраны вызовы loggerSetTimeSource().
//   R09.0: периодическая синхронизация раз в сутки в 11:30.
//   R09.5: ntpSetConfig() — применение серверов без перезагрузки;
//          проверка через sntp_get_sync_status().
//   R09.6: NTP всегда включён (поле ntpUse удалено).
//          Окно синхронизации 1 час, время начала в UI.
//          Фикс s_lastSyncDay — не пропускать плановую
//          синхронизацию после перезагрузки в тот же день.
//   R10.2: - До 3 попыток синхронизации с интервалом 30 мин
//            (третья может выйти за границу окна).
//          - Убрано уведомление о входе в окно — только итог.
//          - Лог: "NTP synced (sched, 1/3)" / "NTP FAILED (sched, 3/3)".
//==============================================================

#ifndef NTP_H
#define NTP_H

#include <Arduino.h>
#include "storage.h"

// Инициализация (в setup(), после wifiInit)
void ntpInit(const Config &cfg);

// Применить новую конфигурацию NTP без перезагрузки
void ntpSetConfig(const Config &cfg);

// Основной цикл — проверяет расписание
void ntpLoop();

// Принудительная синхронизация NTP (кнопка из дашборда)
void ntpForceSync();

// Синхронизировано ли время
bool ntpIsSynced();

// Строки времени
String ntpDateTimeStr();   // "2026-10-12 14:14:40"
String ntpDateStr();       // "2026-10-12"
String ntpTimeStr();       // "14:14:40"

// Unix-время (0, если не синхронизировано)
uint32_t ntpUnixTime();

#endif // NTP_H

//==============================================================

#ifndef WOL_H
#define WOL_H

#include <Arduino.h>
#include "storage.h"
#include "ups.h"

// Инициализация модуля
void wolInit(const Config &cfg);

// Вызывается в loop() на каждом круге.
void wolUpdate(const Config &cfg, const UpsStatus &st);

// Отправить WoL-пакет вручную (для теста из дашборда).
// Возвращает true, если отправка удалась.
bool wolSendManual(const Config &cfg);

// Строка статуса для отображения (русская, для совместимости).
String wolStatusText();

//--------------------------------------------------------------
// R06.1: короткий код статуса для i18n на клиенте.
// Возможные значения:
//   "IDLE"   — ожидание, авария не зафиксирована
//   "SENT"   — пакет отправлен
//   "OUTAGE" — идёт пропадание входа (sec — секунды)
//   "WAIT"   — ожидание стабильного питания
//   "STABLE" — стабильное питание идёт (sec — секунды)
//--------------------------------------------------------------
String wolStatusCode();
uint32_t wolStatusSec();

// Проверка валидности MAC-строки (формат "AA:BB:CC:DD:EE:FF").
bool wolMacValid(const String &mac);

#endif // WOL_H
